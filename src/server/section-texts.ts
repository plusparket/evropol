/** Длина текста без тегов: столько знаков видит посетитель */
export const visibleLength = (html: string) => html.replace(/<[^>]+>/g, '').length;

/** Возвращает список изменений для журнала запуска. */
export async function upgradeSectionTexts(): Promise<string[]> {
  const [done] = await sql`SELECT 1 FROM settings WHERE key = ${FLAG}`;
  if (done) return [];
  const log: string[] = [];
  await sql.begin(async (tx) => {
    for (const [slug, texts] of Object.entries(SECTION_ABOUT)) {
      const res = await tx`UPDATE sections SET ${tx(texts)}, updated_at = now() WHERE slug = ${slug}`;
      if (res.count) log.push(`раздел «${slug}»: новый текст «О покрытии» (${visibleLength(texts.description)} знаков)`);
    }
    await tx`INSERT INTO settings (key, value) VALUES (${FLAG}, '1') ON CONFLICT (key) DO NOTHING`;
  });
  return log;
}
